"""
Packaging of psycodict dump folders into Zenodo-ready artifact sets.

The input is a folder as produced by ``db.copy_to_from_remote`` /
``db.copy_to`` (and consumed by ``db.reload_all``): for each table
``{t}.txt`` plus the optional companions ``{t}_counts.txt``,
``{t}_stats.txt``, ``{t}_indexes.txt``, ``{t}_constraints.txt``,
``{t}_meta.txt``.  Note that the last three contain
the relevant rows of ``meta_indexes``, ``meta_constraints`` and
``meta_tables``, so each record carries everything needed to reconstruct a
fully functional table (the ``meta_*`` tables themselves do not get separate
records).

For each table we produce, in a staging directory:

- each dump file individually compressed (zstd by default, gzip fallback), so
  consumers can fetch e.g. just the schema or the statistics;
  compressed files larger than ``chunk_gb`` are split into parts to keep
  uploads restartable and well under Zenodo's per-file limits
- ``{t}_sample.md`` -- the header (column names, types) and the first few
  rows, uncompressed, so Zenodo's file preview shows something useful
- ``README.md`` -- generated by :mod:`lmfdb.zenodo.metadata` (passed in here)
- ``MANIFEST.json`` -- sizes, md5/sha256 checksums (of both the uncompressed
  sources and the artifacts), row counts, and reassembly instructions

Checksums of the *uncompressed* files are the basis for change detection:
compressed output is not byte-reproducible (multithreaded zstd), so comparing
artifacts would defeat Zenodo's file-level deduplication of unchanged files
across versions.  The orchestrator only re-uploads artifacts whose source
checksum changed.

This module has no LMFDB/sage dependencies (except ``package_knowls``, which
takes a database object) and is exercised by offline tests.
"""

import gzip
import hashlib
import json
import os
import shutil
import subprocess
from datetime import datetime, timezone
from pathlib import Path

# Must match the endings used by psycodict's reload_all/copy_to (1.0 has no
# extras tables, and reload_all refuses a {t}_extras.txt)
COMPANION_ENDINGS = [
    "_counts.txt",
    "_stats.txt",
    "_indexes.txt",
    "_constraints.txt",
    "_meta.txt",
]

# The knowl database is not a search table; it gets one record, updated on
# every data push.  kwl_locks is transient editing state and is not archived.
KNOWL_TABLES = ["kwl_knowls", "kwl_deleted"]

MANIFEST_FORMAT = 1
BLOCKSIZE = 1 << 26  # 64MB


def discover_tables(data_folder):
    """
    The tables present in a dump folder, using the same rule as
    ``reload_all``: every ``*.txt`` file that does not end in one of the
    companion endings names a table.
    """
    data_folder = Path(data_folder)
    tables = []
    for path in sorted(data_folder.glob("*.txt")):
        name = path.name
        if any(name.endswith(end) for end in COMPANION_ENDINGS):
            continue
        tables.append(path.stem)
    return tables


def table_files(data_folder, tablename):
    """
    The dump files for a table present in the folder, as a list of Paths
    (search file first, then companions in canonical order).
    """
    data_folder = Path(data_folder)
    files = []
    main = data_folder / (tablename + ".txt")
    if main.exists():
        files.append(main)
    for end in COMPANION_ENDINGS:
        p = data_folder / (tablename + end)
        if p.exists():
            files.append(p)
    return files


def hash_file(path, count_lines=True):
    """
    Stream a file once, returning ``(size, md5, sha256, nlines)``
    (``nlines`` is None when ``count_lines`` is False).
    """
    md5, sha256 = hashlib.md5(), hashlib.sha256()
    size = 0
    nlines = 0 if count_lines else None
    with open(path, "rb") as F:
        while True:
            block = F.read(BLOCKSIZE)
            if not block:
                break
            size += len(block)
            md5.update(block)
            sha256.update(block)
            if count_lines:
                nlines += block.count(b"\n")
    return size, md5.hexdigest(), sha256.hexdigest(), nlines


def data_rows(path, nlines):
    """
    Number of data rows in a dump file with ``nlines`` lines: the search
    file ``{t}.txt`` (and the knowl dumps) start with 3 header lines (column
    names, column types, blank), the companion files have none, and non-.txt
    files return None.
    """
    name = os.path.basename(str(path))
    if not name.endswith(".txt"):
        return None
    if any(name.endswith(end) for end in COMPANION_ENDINGS):
        return nlines
    return max(nlines - 3, 0)


def copy_fields(line, sep="|"):
    """The fields of a PostgreSQL COPY text-format line (escapes kept)."""
    fields, cur, i = [], [], 0
    while i < len(line):
        if line[i] == "\\" and i + 1 < len(line):
            cur.append(line[i:i + 2])
            i += 2
            continue
        if line[i] == sep:
            fields.append("".join(cur))
            cur = []
        else:
            cur.append(line[i])
        i += 1
    fields.append("".join(cur))
    return fields


def write_sample(searchfile, dst, max_rows=10, max_bytes=500000, keep=None,
                 chosen="the first rows"):
    """
    Write a Markdown preview of a search file to ``dst``: its first data row
    field by field, then its three header lines and up to ``max_rows`` data
    rows as stored.  Rows can be enormous (jsonb columns), so the raw part is
    capped at ``max_bytes`` and the field values at 300 characters.

    - ``keep`` -- if given, only rows ``r`` (a dict by column name) with
      ``keep(r)`` true are shown, described as ``chosen``

    The preview is Markdown rather than ``.txt`` because ``reload_all``
    treats every ``.txt`` file in a folder as a table to load.
    """
    searchfile = Path(searchfile)
    with open(searchfile, encoding="utf-8", errors="replace") as F:
        header = [F.readline().rstrip("\n") for _ in range(3)]
        names, types = copy_fields(header[0]), copy_fields(header[1])
        rows, written = [], 0
        for line in F:
            line = line.rstrip("\n")
            if keep is not None and not keep(dict(zip(names, copy_fields(line)))):
                continue
            if written + len(line) > max_bytes:
                rows.append(line[:max(max_bytes - written, 0)])
                rows.append("... (truncated for preview)")
                break
            rows.append(line)
            written += len(line)
            if len(rows) >= max_rows:
                break
    out = ["# Sample of `%s`" % searchfile.stem, ""]
    if rows:
        out += ["The first of %s, field by field (`\\N` is NULL):" % chosen, "",
                "| column | type | value |", "|---|---|---|"]
        for name, typ, value in zip(names, types, copy_fields(rows[0])):
            if len(value) > 300:
                value = value[:300] + " ..."
            out.append("| `%s` | `%s` | %s |" % (
                name, typ, value.replace("|", "\\|").replace("`", "'")))
        out.append("")
    out += ["The header of `%s` (column names, column types, a blank line) "
            "and %s, as stored (`|`-separated, in PostgreSQL COPY format):"
            % (searchfile.name, chosen), ""]
    out += ["    " + line for line in header + rows]
    with open(dst, "w", encoding="utf-8") as G:
        G.write("\n".join(out) + "\n")
    return dst


def zstd_available():
    return shutil.which("zstd") is not None


def compress_file(src, dst_dir, level=12, force_gzip=False):
    """
    Compress ``src`` into ``dst_dir``, returning the artifact Path
    (``{name}.zst`` via the zstd CLI when available, else ``{name}.gz``).
    """
    src, dst_dir = Path(src), Path(dst_dir)
    if not force_gzip and zstd_available():
        dst = dst_dir / (src.name + ".zst")
        subprocess.run(
            ["zstd", "-q", "-f", "-%d" % level, "-T0", "-o", str(dst), str(src)],
            check=True,
        )
    else:
        dst = dst_dir / (src.name + ".gz")
        # mtime=0 keeps the output byte-identical across runs, so that an
        # unchanged file is not uploaded again
        with open(src, "rb") as F, gzip.GzipFile(dst, "wb", mtime=0,
                                                 compresslevel=min(level, 9)) as G:
            shutil.copyfileobj(F, G, BLOCKSIZE)
    return dst


def split_file(path, chunk_bytes):
    """
    Split ``path`` into ``{path}.partNNN`` pieces of at most ``chunk_bytes``
    if it is larger than ``chunk_bytes`` (removing the original), returning
    the list of part Paths; otherwise return ``[path]`` unchanged.
    """
    if chunk_bytes <= 0:
        raise ValueError("chunk size must be positive, not %s" % chunk_bytes)
    path = Path(path)
    if path.stat().st_size <= chunk_bytes:
        return [path]
    parts = []
    with open(path, "rb") as F:
        i = 0
        while True:
            part = path.with_name("%s.part%03d" % (path.name, i))
            remaining = chunk_bytes
            with open(part, "wb") as G:
                while remaining > 0:
                    block = F.read(min(BLOCKSIZE, remaining))
                    if not block:
                        break
                    G.write(block)
                    remaining -= len(block)
            if part.stat().st_size == 0:
                part.unlink()
                break
            parts.append(part)
            i += 1
    path.unlink()
    return parts


def _package_files(name, sources, outdir, chunk_bytes, level, force_gzip,
                   readme=None, sample_source=None, extra_manifest=None,
                   sample_options=None):
    """
    Shared packaging core: compress+split each source file into ``outdir``,
    write the sample, README and MANIFEST.json, and return the manifest dict.

    ``readme`` is the README's text, or a function of the manifest returning
    it.  ``outdir`` is wiped first (it is a per-record staging area).
    """
    outdir = Path(outdir)
    if outdir.exists():
        shutil.rmtree(outdir)
    outdir.mkdir(parents=True)

    compression = "gzip" if (force_gzip or not zstd_available()) else "zstd"
    manifest = {
        "format": MANIFEST_FORMAT,
        "name": name,
        "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "sep": "|",
        "compression": compression,
        "compression_level": level,
        "source_files": {},
        "artifacts": [],
    }
    if extra_manifest:
        manifest.update(extra_manifest)

    for src in sources:
        src = Path(src)
        size, md5, sha256, nlines = hash_file(src)
        manifest["source_files"][src.name] = {
            "size": size,
            "md5": md5,
            "sha256": sha256,
            "rows": data_rows(src, nlines),
        }
        artifact = compress_file(src, outdir, level=level, force_gzip=force_gzip)
        asize, amd5, asha256, _ = hash_file(artifact, count_lines=False)
        entry = {
            "name": artifact.name,
            "source": src.name,
            "size": asize,
            "md5": amd5,
            "sha256": asha256,
        }
        parts = split_file(artifact, chunk_bytes)
        if parts != [artifact]:
            entry["parts"] = []
            for part in parts:
                psize, pmd5, _, _ = hash_file(part, count_lines=False)
                entry["parts"].append(
                    {"name": part.name, "size": psize, "md5": pmd5})
            entry["reassemble"] = "cat %s.part* > %s" % (artifact.name,
                                                         artifact.name)
        manifest["artifacts"].append(entry)

    if sample_source is not None:
        sample = outdir / (name + "_sample.md")
        write_sample(sample_source, sample, **(sample_options or {}))
        manifest["sample"] = sample.name
    if readme is not None:
        with open(outdir / "README.md", "w") as F:
            F.write(readme(manifest) if callable(readme) else readme)

    with open(outdir / "MANIFEST.json", "w") as F:
        json.dump(manifest, F, indent=2)
        F.write("\n")
    return manifest


def upload_list(outdir):
    """
    The files of a packaged record in upload order: README and sample first
    (they sort first alphabetically on Zenodo too, making the README the
    default preview), then MANIFEST.json, then artifacts/parts.
    """
    outdir = Path(outdir)
    names = sorted(os.listdir(outdir))
    priority = {"README.md": 0, "MANIFEST.json": 2}
    return [outdir / n for n in sorted(
        names, key=lambda n: (priority.get(n, 1 if n.endswith("_sample.md") else 3), n))]


def package_table(data_folder, tablename, staging_dir, chunk_gb=20, level=12,
                  force_gzip=False, readme=None, record_version=None,
                  extra_manifest=None):
    """
    Package one table's dump files from ``data_folder`` into
    ``{staging_dir}/{tablename}/``; returns the manifest dict.

    INPUT:

    - ``data_folder`` -- the folder given to ``reload_all``
    - ``tablename`` -- which table to package
    - ``staging_dir`` -- parent directory for the per-record staging folders
    - ``chunk_gb`` -- split compressed artifacts larger than this many
      (decimal) GB
    - ``level`` -- zstd compression level
    - ``force_gzip`` -- use gzip even if zstd is available (mainly for tests)
    - ``readme`` -- contents for README.md, or a function of the manifest
      returning them (see lmfdb.zenodo.metadata)
    - ``record_version`` -- the record's own version (e.g. "1.4")
    - ``extra_manifest`` -- more entries for MANIFEST.json (provenance)
    """
    sources = table_files(data_folder, tablename)
    if not sources or sources[0].name != tablename + ".txt":
        raise ValueError("no dump files for %s in %s" % (tablename, data_folder))
    return _package_files(
        tablename, sources, Path(staging_dir) / tablename,
        chunk_bytes=int(chunk_gb * 10**9), level=level, force_gzip=force_gzip,
        readme=readme, sample_source=sources[0],
        extra_manifest=dict(extra_manifest or {}, record_version=record_version),
    )


def files_time(data_folder, tablename):
    """When a table's dump files were last written, as naive UTC."""
    mtime = max(p.stat().st_mtime for p in table_files(data_folder, tablename))
    return datetime.fromtimestamp(mtime, timezone.utc).replace(tzinfo=None)


def source_md5s(data_folder, tablename):
    """
    ``{filename: md5}`` of a table's uncompressed dump files -- the change
    detection key, compared against ``userdb.zenodo_backups.source_md5s``
    without packaging anything.
    """
    return {src.name: hash_file(src, count_lines=False)[1]
            for src in table_files(data_folder, tablename)}


