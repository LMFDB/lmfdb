def dump_knowls(db, dump_folder, sep="|"):
    """
    Dump the knowl tables (see ``KNOWL_TABLES``) to ``dump_folder`` in the
    same format psycodict uses (header lines with column names and types,
    then ``COPY``-formatted rows, sorted so that unchanged knowls give an
    identical file), together with ``{t}_schema.sql`` files recording CREATE
    TABLE statements.  Returns the list of files written.

    Unlike search tables, the knowl database is updated live on the website,
    so this is called at backup time to snapshot its current state.
    """
    from psycodict import SQL, Identifier
    from psycodict.utils import DelayCommit

    dump_folder = Path(dump_folder)
    dump_folder.mkdir(parents=True, exist_ok=True)
    written = []
    # one transaction (a consistent snapshot), committed on leaving the
    # block rather than left open on the connection
    with DelayCommit(db):
        for tname in KNOWL_TABLES:
            # format_type gives complete types (text[], not information_schema's ARRAY)
            cur = db._execute(SQL(
                "SELECT attname, pg_catalog.format_type(atttypid, atttypmod) "
                "FROM pg_catalog.pg_attribute WHERE attrelid = to_regclass(%s) "
                "AND attnum > 0 AND NOT attisdropped ORDER BY attnum"),
                ["public." + tname])
            cols = [(name, typ) for name, typ in cur]
            if not cols:
                raise ValueError("table %s not found" % tname)
            names = [name for name, _ in cols]
            datafile = dump_folder / (tname + ".txt")
            # text casts make every column sortable (json has no ordering)
            select = SQL("SELECT {0} FROM {1} ORDER BY {2}").format(
                SQL(", ").join(Identifier(name) for name in names),
                Identifier(tname),
                SQL(", ").join(SQL("{0}::text").format(Identifier(name))
                               for name in names))
            db._copy_to_select(
                select, str(datafile), sep=sep, silent=True,
                header="%s\n%s\n\n" % (sep.join(names),
                                        sep.join(typ for _, typ in cols)))
            schemafile = dump_folder / (tname + "_schema.sql")
            with open(schemafile, "w") as F:
                F.write("CREATE TABLE %s (\n    %s\n);\n" % (
                    tname,
                    ",\n    ".join("%s %s" % (name, typ) for name, typ in cols)))
            written.extend([datafile, schemafile])
    return written


def shown_knowls(path):
    """
    The ``(id, timestamp)`` of the latest reviewed revision of each knowl in
    a ``kwl_knowls`` dump: the text www.lmfdb.org shows for it.
    """
    latest = {}
    with open(path, encoding="utf-8", errors="replace") as F:
        names = copy_fields(F.readline().rstrip("\n"))
        F.readline()
        F.readline()
        for line in F:
            row = dict(zip(names, copy_fields(line.rstrip("\n"))))
            if row.get("status") == "1" and row.get("timestamp", "") > latest.get(row["id"], ""):
                latest[row["id"]] = row["timestamp"]
    return set(latest.items())


def package_knowls(db, staging_dir, chunk_gb=20, level=12, force_gzip=False,
                   readme=None, record_version=None, extra_manifest=None):
    """
    Dump and package the knowl database as one record ("lmfdb_knowls");
    returns the manifest dict.
    """
    staging_dir = Path(staging_dir)
    dump_folder = staging_dir / "lmfdb_knowls_dump"
    if dump_folder.exists():
        shutil.rmtree(dump_folder)
    files = dump_knowls(db, dump_folder)
    knowls = dump_folder / (KNOWL_TABLES[0] + ".txt")
    shown = shown_knowls(knowls)
    manifest = _package_files(
        "lmfdb_knowls", files, staging_dir / "lmfdb_knowls",
        chunk_bytes=int(chunk_gb * 10**9), level=level, force_gzip=force_gzip,
        readme=readme, sample_source=knowls,
        sample_options={
            "keep": lambda r: (r.get("id"), r.get("timestamp")) in shown,
            "chosen": "the knowls as www.lmfdb.org shows them (the latest "
                      "reviewed revision of each)"},
        extra_manifest=dict(extra_manifest or {}, knowl_tables=KNOWL_TABLES,
                            record_version=record_version),
    )
    shutil.rmtree(dump_folder)
    return manifest
